-- Maestro Qi 咨询档案表（在 Supabase Dashboard → SQL Editor 里整段执行一次）
--
-- 说明：
-- 1) master_qi_records_identity_unique 是必须的：应用用 on_conflict=name,birth_info,ptype
--    做“同一个人 + 同一次测算”覆盖更新，没有唯一约束就无法 upsert。
-- 2) report / history 都是 text，没有 Google Sheets 单元格 5 万字符的限制。
-- 3) 开启 RLS 且不建任何策略，等价于“只有 service_role 能读写”，
--    anon key 拿不到数据。API Key 只放在 Streamlit Secrets 里，不要进仓库。

create table if not exists public.master_qi_records (
    id          bigint generated by default as identity primary key,
    name        text        not null,
    birth_info  text        not null,
    ptype       text        not null default 'single',
    report      text        not null default '',
    history     text        not null default '[]',
    date        text,
    constraint master_qi_records_identity_unique unique (name, birth_info, ptype)
);

alter table public.master_qi_records enable row level security;

-- 撤销匿名/普通登录用户的权限，只留给 service_role。
revoke all on public.master_qi_records from anon, authenticated;
grant all on public.master_qi_records to service_role;
grant usage, select on all sequences in schema public to service_role;

-- 可选：按姓名检索更快（历史档案列表仍由应用在 Python 侧过滤）。
create index if not exists master_qi_records_name_idx on public.master_qi_records (name);
